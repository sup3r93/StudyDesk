using System.IO;
using System.Security.Cryptography;
using System.Text.Json;
using StudyDesk.Desktop.Configuration;

namespace StudyDesk.Desktop.Synchronization;

/// <summary>Persists a user-approved association without exposing its token to source or renderer.</summary>
public sealed class ConnectionStore
{
    private static readonly JsonSerializerOptions JsonOptions = new(JsonSerializerDefaults.Web);
    private readonly DesktopSettings settings;

    /// <summary>Creates an association store using paths supplied by private environment configuration.</summary>
    public ConnectionStore(DesktopSettings settings)
    {
        this.settings = settings ?? throw new ArgumentNullException(nameof(settings));
    }

    /// <summary>Reads authoritative metadata from the same protected file as its credential.</summary>
    public ServerConnection? LoadConnection()
    {
        return File.Exists(settings.TokenFile) ? ReadAssociation().Connection : null;
    }

    /// <summary>Returns a credential only when its protected association matches the selected server.</summary>
    public string LoadToken(ServerConnection connection)
    {
        ArgumentNullException.ThrowIfNull(connection);
        ProtectedAssociation saved = ReadAssociation();
        if (saved.Connection != connection)
        {
            throw new InvalidOperationException("The protected server association does not match its metadata.");
        }

        return saved.Token;
    }

    /// <summary>Protects metadata and credential together, then replaces their single authoritative file.</summary>
    public void Save(ServerConnection connection, string token)
    {
        ArgumentNullException.ThrowIfNull(connection);
        ValidateToken(token);
        byte[] plain = JsonSerializer.SerializeToUtf8Bytes(new ProtectedAssociation(connection, token), JsonOptions);
        try
        {
            byte[] encrypted = ProtectedData.Protect(plain, null, DataProtectionScope.CurrentUser);
            WriteAtomically(settings.TokenFile, encrypted);
            // This human-readable copy is advisory; recovery always uses the single protected file.
            try
            {
                WriteAtomically(settings.ConnectionFile, JsonSerializer.SerializeToUtf8Bytes(connection, JsonOptions));
            }
            catch (Exception error) when (error is IOException or UnauthorizedAccessException)
            {
                // The verified, protected association is already durable and remains authoritative.
            }
        }
        finally
        {
            CryptographicOperations.ZeroMemory(plain);
        }
    }

    /// <summary>Decrypts one bounded association for the current Windows user only.</summary>
    private ProtectedAssociation ReadAssociation()
    {
        PrivateDirectoryPolicy.ValidateExistingFile(settings.TokenFile);
        FileInfo info = new(settings.TokenFile);
        if (info.Length > 65536)
        {
            throw new InvalidOperationException("The protected association file exceeds its supported size.");
        }

        byte[] plain = ProtectedData.Unprotect(File.ReadAllBytes(settings.TokenFile), null, DataProtectionScope.CurrentUser);
        try
        {
            ProtectedAssociation association = JsonSerializer.Deserialize<ProtectedAssociation>(plain, JsonOptions)
                ?? throw new InvalidOperationException("The protected association is empty.");
            ValidateToken(association.Token);
            ArgumentNullException.ThrowIfNull(association.Connection);
            return association;
        }
        finally
        {
            CryptographicOperations.ZeroMemory(plain);
        }
    }

    /// <summary>Groups the credential with its destination to prevent torn cross-server associations.</summary>
    /// <param name="Connection">The verified server and history generation.</param>
    /// <param name="Token">The credential protected by Windows before persistence.</param>
    private sealed record ProtectedAssociation(ServerConnection Connection, string Token);

    /// <summary>Rejects malformed credentials without including their contents in an error.</summary>
    public static void ValidateToken(string token)
    {
        if (token is null || token.Length != 64 || token.Any(character => !Uri.IsHexDigit(character)))
        {
            throw new ArgumentException("Enter the 64-character token generated by your server.", nameof(token));
        }
    }

    /// <summary>Flushes a private temporary file before replacing an existing association file.</summary>
    private static void WriteAtomically(string path, byte[] content)
    {
        string directory = Path.GetDirectoryName(path) ?? throw new InvalidOperationException("An association directory is required.");
        PrivateDirectoryPolicy.Ensure(directory);
        string temporary = path + "." + Guid.NewGuid().ToString("N") + ".tmp";
        try
        {
            using (FileStream stream = new(temporary, FileMode.CreateNew, FileAccess.Write, FileShare.None))
            {
                stream.Write(content);
                stream.Flush(true);
            }

            File.Move(temporary, path, true);
        }
        finally
        {
            if (File.Exists(temporary))
            {
                File.Delete(temporary);
            }
        }
    }
}
